"""Generate tables/equivalent_physical.tex and macros/physical_numbers.tex from
frozen benchmark outputs. Reads *.runs.jsonl / *.manifest.json / *.complete.json
only; never edits section files (update_db_draft.py did, and must not be rerun).
"""
import hashlib, json, statistics
from pathlib import Path

repo = Path(__file__).resolve().parents[1]
dirs = [repo / 'results/efficiency']
(repo / 'tables').mkdir(exist_ok=True)
(repo / 'macros').mkdir(exist_ok=True)
order = [('graphrag-bench-medical_q100', 'Medical'), ('mix', 'Mix'), ('graphrag-bench-novel_q100', 'Novel'),
         ('agriculture', 'Agriculture'), ('legal_q100', 'Legal'), ('musique_q100', 'MuSiQue')]
med = statistics.median


def load(ds):
    for d in dirs:
        done = d / (ds + '.complete.json')
        if done.exists():
            rp = d / (ds + '.runs.jsonl')
            marker = json.loads(done.read_text())
            assert hashlib.sha256(rp.read_bytes()).hexdigest() == marker['runs_sha256']
            rows = [json.loads(l) for l in rp.read_text().splitlines()]
            assert len(rows) == marker['rows'] and all(r['equal_to_eager'] for r in rows)
            return rows, json.loads((d / (ds + '.manifest.json')).read_text()), rp
    return None


def stats(rows, m, b, mode):
    r = [x for x in rows if x['budget'] == b and x['mode'] == mode]
    first = [x for x in r if x['cycle'] == 0]
    warm = [x for x in r if x['cycle'] == m['cycles'] - 1]
    assert len(first) == len(warm) == m['repeats']
    return {'cold_s': med(x['upfront_seconds'] + x['service_seconds'] for x in first),
            'cold_p95_ms': med(x['query_p95_ms'] for x in first),
            'warm_ms': med(x['service_seconds'] / x['queries'] * 1000 for x in warm),
            'MB': med(x['payload_resident_bytes'] / 1e6 for x in first),
            'warm_misses': med(x['cache_misses'] for x in warm)}


lines = [r'% Generated by scripts/gen_physical_table.py from frozen benchmark runs.']
body, ratios, summary, inputs = [], [], {}, {}
for ds, label in order:
    got = load(ds)
    if got is None:
        continue
    rows, m, rp = got
    inputs[ds] = hashlib.sha256(rp.read_bytes()).hexdigest()
    for b in [0, 8]:
        s = {mode: stats(rows, m, b, mode) for mode in ['eager', 'lazy_unbounded', 'lazy_lru_1pct', 'lazy_lru_10pct', 'no_cache']}
        summary[f'{ds}/{b}'] = s
        e, l, n = s['eager'], s['lazy_unbounded'], s['no_cache']
        if b == 0:
            ratios.append(e['cold_s'] / l['cold_s'])
        depth = r'$\infty$' if b == 0 else '$8$'
        body.append(f"{label} & {depth} & {e['cold_s']:.3f} & {l['cold_s']:.3f} & {100 * l['MB'] / e['MB']:.2f} & "
                    f"{e['warm_ms']:.4f} & {l['warm_ms']:.4f} & {n['warm_ms']:.2f} & {e['cold_p95_ms']:.3f} & {l['cold_p95_ms']:.2f} " + r'\\')
for x in inputs.items():
    lines.append(f'% runs sha256 {x[0]}: {x[1]}')
lines += [r'\begin{table*}[t]', r'\centering\small',
          r'\caption{Equivalent navigation-view implementations on reconstructed request traces. Cold total includes eager construction; warm service is the third replay; cold P95 is the 95th-percentile per-question service time in the first replay. Values are medians over five runs. Storage counts serialized navigation values, excluding keys, runtime overhead, and the shared graph. This is a view-service microbenchmark, not end-to-end QA latency.}',
          r'\label{tab:physical-cache}', r'\setlength{\tabcolsep}{4pt}', r'\begin{tabular}{llrrrrrrrr}', r'\toprule',
          r'Corpus & Depth & \multicolumn{2}{c}{Cold total (s)} & Lazy storage & \multicolumn{3}{c}{Warm service (ms/question)} & \multicolumn{2}{c}{Cold P95 (ms/question)} \\',
          r'\cmidrule(lr){3-4}\cmidrule(lr){6-8}\cmidrule(lr){9-10}',
          r' & & Eager & Lazy+cache & (\% of eager) & Eager & Lazy+cache & No cache & Eager & Lazy+cache \\', r'\midrule']
lines += body + [r'\bottomrule', r'\end{tabular}', r'\end{table*}']
(repo / 'tables/equivalent_physical.tex').write_text('\n'.join(lines) + '\n')
(repo / 'macros/physical_numbers.tex').write_text('% Generated by scripts/gen_physical_table.py; not end-to-end speedups.\n'
    + r'\newcommand{\PhysicalColdMin}{' + f'{min(ratios):.0f}' + '}\n' + r'\newcommand{\PhysicalColdMax}{' + f'{max(ratios):.0f}' + '}\n')
print(json.dumps({'ratios_binf': [round(r, 1) for r in ratios]}, indent=0))
for k, s in summary.items():
    print(k, {m: {kk: round(v, 4) for kk, v in d.items()} for m, d in s.items()})
